// ─── BEAN Classroom Intelligence (CI-6B): real expert application & onboarding ──
// Activation layer on the existing CI-5 reviewer pipeline. This module owns the
// APPLICANT side of onboarding: application detail, protected credential
// evidence, the information-request loop, explicit consent and withdrawal.
//
// It deliberately does NOT touch:
//   • the qualification decision path (decideReviewerQualification, CI-5B),
//   • reviewer scope writes (admin-only, CI-5B),
//   • reviewer assignment eligibility (isReviewerAssignableStatus — only an
//     ACTIVE reviewer takes expert work; an APPLICATION_PENDING applicant can
//     never claim assignments).
//
// Evidence hygiene invariants:
//   • Files live in the RESTRICTED evidence store (db/evidence/, mode 0600),
//     referenced by id + sha256 — never in /public, never served by ordinary
//     profile endpoints, never embedded in logs (metadata only).
//   • Allowed content types are sniffed from magic bytes, not client MIME
//     strings: PDF (%PDF-), PNG, JPEG. Hard size cap. Rate limiting lives at
//     the route (shared rate-limit helper).
//   • Possession of an uploaded document is never treated as proof of its
//     authenticity — verification is a separate human process (CI-6C).
//   • Withdrawal purges file bytes but keeps metadata + hash (retentionState
//     PURGED) so the audit trail stays truthful.

import { z } from 'zod'
import { createHash, randomUUID } from 'node:crypto'
import { mkdir, unlink, writeFile, stat, chmod } from 'node:fs/promises'
import path from 'node:path'
import type { ReviewerProfileRow, ReviewerEventType } from './reviewers'
import { REVIEWER_TRANSITIONS } from './reviewers'

// ─── Vocabularies ──────────────────────────────────────────────────────────────

/** Credential evidence kinds (metadata only; content is sniffed, not declared). */
export const EVIDENCE_KINDS = [
  'CV',
  'CERTIFICATE',
  'LICENCE',
  'EMPLOYMENT_RECORD',
  'PUBLICATION',
  'REFERENCE',
  'OTHER',
] as const
export type EvidenceKind = (typeof EVIDENCE_KINDS)[number]

export const EVIDENCE_RETENTION = ['ACTIVE', 'PURGED'] as const

export const INFO_REQUEST_STATUS = ['OPEN', 'ANSWERED'] as const

/** Hard evidence size cap: 10 MiB — credentials, not media libraries. */
export const EVIDENCE_MAX_BYTES = 10 * 1024 * 1024

/** Application states in which the applicant may still edit/withdraw. */
const OPEN_APPLICATION_STATUSES = ['APPLICATION_PENDING', 'QUALIFICATION_REVIEW'] as const

// ─── Restricted evidence store (filesystem) ────────────────────────────────────

const DEFAULT_EVIDENCE_ROOT = path.join(process.cwd(), 'db', 'evidence')

/** Sniff content type from magic bytes — client-supplied MIME is never trusted. */
export function sniffEvidenceMime(bytes: Uint8Array): 'application/pdf' | 'image/png' | 'image/jpeg' | null {
  if (bytes.length >= 5 && bytes[0] === 0x25 && bytes[1] === 0x50 && bytes[2] === 0x44 && bytes[3] === 0x46 && bytes[4] === 0x2d) {
    return 'application/pdf' // %PDF-
  }
  if (
    bytes.length >= 8 &&
    bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47 &&
    bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a
  ) {
    return 'image/png'
  }
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) {
    return 'image/jpeg'
  }
  return null
}

const MIME_EXTENSION: Record<string, string> = {
  'application/pdf': '.pdf',
  'image/png': '.png',
  'image/jpeg': '.jpg',
}

function evidenceRoot(rootOverride?: string): string {
  return rootOverride ?? DEFAULT_EVIDENCE_ROOT
}

/** Absolute path of an evidence file inside the restricted store. */
export function evidenceFilePath(storagePath: string, rootOverride?: string): string {
  // storagePath is generated by this module ("evidence/<id><ext>"); reject any
  // path that tries to escape the store (defence in depth against tampered rows).
  const resolved = path.resolve(evidenceRoot(rootOverride), storagePath)
  if (!resolved.startsWith(path.resolve(evidenceRoot(rootOverride)) + path.sep)) {
    throw new Error('evidence storage path escaped the restricted store')
  }
  return resolved
}

// ─── Structural DB view ────────────────────────────────────────────────────────

export interface EvidenceRow {
  id: string
  profileId: string
  kind: string
  fileName: string
  byteSize: number
  sha256: string
  mimeType: string
  storagePath: string
  retentionState: string
  purgedAt: Date | null
  purgedReason: string | null
  uploadedByStudentId: string
  createdAt: Date
}

export interface InfoRequestRow {
  id: string
  profileId: string
  requestText: string
  status: string
  responseText: string | null
  requestedByAdminId: string
  requestedAt: Date
  answeredAt: Date | null
  createdAt: Date
  updatedAt: Date
}

export interface ApplicationsDb {
  expertReviewerProfile: {
    findUnique(args: { where: Record<string, unknown> }): Promise<ReviewerProfileRow | null>
    update(args: { where: Record<string, unknown>; data: Record<string, unknown> }): Promise<ReviewerProfileRow>
  }
  expertReviewerEvent: {
    create(args: { data: Record<string, unknown> }): Promise<Record<string, unknown>>
    findMany(args?: Record<string, unknown>): Promise<Array<{ id: string; profileId: string; eventType: string; actorKind: string; actorId: string; rationale: string | null; payload: string | null; createdAt: Date }>>
  }
  expertCredentialEvidence: {
    create(args: { data: Record<string, unknown> }): Promise<EvidenceRow>
    findUnique(args: { where: Record<string, unknown> }): Promise<EvidenceRow | null>
    findMany(args?: Record<string, unknown>): Promise<EvidenceRow[]>
    update(args: { where: Record<string, unknown>; data: Record<string, unknown> }): Promise<EvidenceRow>
  }
  expertApplicationInfoRequest: {
    create(args: { data: Record<string, unknown> }): Promise<InfoRequestRow>
    findUnique(args: { where: Record<string, unknown> }): Promise<InfoRequestRow | null>
    findMany(args?: Record<string, unknown>): Promise<InfoRequestRow[]>
    update(args: { where: Record<string, unknown>; data: Record<string, unknown> }): Promise<InfoRequestRow>
  }
}

export function applicationsDbFromPrisma(client: unknown): ApplicationsDb {
  const c = client as {
    expertReviewerProfile: ApplicationsDb['expertReviewerProfile']
    expertReviewerEvent: ApplicationsDb['expertReviewerEvent']
    expertCredentialEvidence: ApplicationsDb['expertCredentialEvidence']
    expertApplicationInfoRequest: ApplicationsDb['expertApplicationInfoRequest']
  }
  return c
}

export type ApplicationOpResult<T = undefined> =
  | { ok: true; profile?: ReviewerProfileRow; value?: T; evidence?: EvidenceRow; request?: InfoRequestRow }
  | { ok: false; status: number; error: string }

function actorEvent(db: ApplicationsDb, profileId: string, eventType: ReviewerEventType, actorKind: 'REVIEWER' | 'ADMIN', actorId: string, rationale: string, payload?: Record<string, unknown>): Promise<unknown> {
  return db.expertReviewerEvent.create({
    data: {
      profileId,
      eventType,
      actorKind,
      actorId,
      rationale: rationale.slice(0, 2000),
      payload: payload ? JSON.stringify(payload) : null,
    },
  })
}

function parseJsonArray(raw: string | null | undefined): string[] {
  if (!raw) return []
  try {
    const v = JSON.parse(raw) as unknown
    return Array.isArray(v) ? (v.filter((x) => typeof x === 'string') as string[]) : []
  } catch {
    return []
  }
}

// ─── Application detail (edit while open; review-before-submit snapshot) ──────

export const applicationUpdateSchema = z.object({
  qualificationCategory: z.string().max(160).optional(),
  professionalExperience: z.string().max(2000).optional(),
  issuingBody: z.string().max(160).optional(),
  institutionAffiliation: z.string().max(200).optional(),
  specialties: z.array(z.string().min(1).max(80)).max(12).optional(),
  conflictOfInterest: z.string().min(4).max(2000).optional(),
  /** Consent can be granted (literal true) but never revoked silently here. */
  consentGranted: z.literal(true).optional(),
}).strict()

/**
 * Update the open application's own detail fields. Identity comes from the
 * server-resolved profile; no status/verification/scope field is writable
 * through this path — those remain admin-only (CI-5B) authorities.
 */
export async function updateExpertApplication(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
  input: unknown,
): Promise<ApplicationOpResult> {
  const parsed = applicationUpdateSchema.safeParse(input)
  if (!parsed.success) {
    const first = parsed.error.issues[0]
    return { ok: false, status: 400, error: `invalid application update: ${first?.path.join('.') ?? '?'} — ${first?.message ?? 'schema mismatch'}` }
  }
  const profile = await db.expertReviewerProfile.findUnique({ where: { studentId: actor.studentId } })
  if (!profile) return { ok: false, status: 404, error: 'no expert application exists for this account' }
  if (!OPEN_APPLICATION_STATUSES.includes(profile.status as (typeof OPEN_APPLICATION_STATUSES)[number])) {
    return { ok: false, status: 409, error: `application is ${profile.status} — the detail is frozen once a decision or withdrawal exists` }
  }
  const data = parsed.data
  const coiChanged = data.conflictOfInterest !== undefined && data.conflictOfInterest !== profile.conflictOfInterest
  const updated = await db.expertReviewerProfile.update({
    where: { id: profile.id },
    data: {
      qualificationCategory: data.qualificationCategory ?? profile.qualificationCategory,
      professionalExperience: data.professionalExperience ?? profile.professionalExperience,
      issuingBody: data.issuingBody ?? profile.issuingBody,
      institutionAffiliation: data.institutionAffiliation ?? profile.institutionAffiliation,
      specialtiesJson: data.specialties ? JSON.stringify(data.specialties) : profile.specialtiesJson,
      conflictOfInterest: data.conflictOfInterest ?? profile.conflictOfInterest,
      applicationConsentAt: data.consentGranted === true && !profile.applicationConsentAt ? new Date() : profile.applicationConsentAt,
    },
  })
  await actorEvent(db, profile.id, 'APPLICATION_SUBMITTED', 'REVIEWER', actor.studentId, 'application detail updated by applicant', {
    updatedFields: Object.keys(data),
    institutionAffiliation: updated.institutionAffiliation,
    specialties: parseJsonArray(updated.specialtiesJson),
    consentGranted: updated.applicationConsentAt !== null,
  })
  if (coiChanged) {
    await actorEvent(db, profile.id, 'COI_DECLARED', 'REVIEWER', actor.studentId, (data.conflictOfInterest ?? '').slice(0, 2000))
  }
  if (data.consentGranted === true && !profile.applicationConsentAt) {
    await actorEvent(db, profile.id, 'CONSENT_RECORDED', 'REVIEWER', actor.studentId, 'applicant reviewed the exact submitted information and its intended use (credential verification + reviewer process) and consented')
  }
  return { ok: true, profile: updated }
}

// ─── Credential evidence (protected upload path) ──────────────────────────────

export interface EvidenceUploadInput {
  kind: EvidenceKind
  fileName: string
  bytes: Uint8Array
}

/**
 * Record an evidence upload: writes the file into the restricted store
 * (0600, random id name), stores metadata + sha256, appends an
 * EVIDENCE_UPLOADED event whose payload carries metadata only — never content.
 */
export async function recordEvidenceUpload(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
  input: EvidenceUploadInput,
  options: { storeRoot?: string } = {},
): Promise<ApplicationOpResult<EvidenceRow>> {
  const kindOk = (EVIDENCE_KINDS as readonly string[]).includes(input.kind)
  if (!kindOk) return { ok: false, status: 400, error: `invalid evidence kind (allowed: ${EVIDENCE_KINDS.join(', ')})` }
  if (!input.fileName || input.fileName.length > 200) return { ok: false, status: 400, error: 'evidence fileName required (max 200 chars)' }
  if (!input.bytes || input.bytes.length === 0) return { ok: false, status: 400, error: 'evidence file is empty' }
  if (input.bytes.length > EVIDENCE_MAX_BYTES) {
    return { ok: false, status: 413, error: `evidence file exceeds the ${Math.floor(EVIDENCE_MAX_BYTES / (1024 * 1024))} MiB limit` }
  }
  const mime = sniffEvidenceMime(input.bytes)
  if (!mime) {
    return { ok: false, status: 415, error: 'unsupported evidence content — only PDF, PNG and JPEG are accepted (validated from file content, not the declared type)' }
  }
  const profile = await db.expertReviewerProfile.findUnique({ where: { studentId: actor.studentId } })
  if (!profile) return { ok: false, status: 404, error: 'no expert application exists for this account' }
  if (!OPEN_APPLICATION_STATUSES.includes(profile.status as (typeof OPEN_APPLICATION_STATUSES)[number])) {
    return { ok: false, status: 409, error: `application is ${profile.status} — evidence can only be attached while the application is open` }
  }
  if (profile.studentId !== actor.studentId) {
    return { ok: false, status: 403, error: 'evidence belongs to a different account' }
  }

  const sha256 = createHash('sha256').update(input.bytes).digest('hex')
  const id = `ev_${randomUUID().replace(/-/g, '')}`
  const ext = MIME_EXTENSION[mime] ?? '.bin'
  // Relative to the restricted store root (db/evidence/) — never an absolute
  // path, never the client-supplied name.
  const storagePath = `${id}${ext}`
  const root = evidenceRoot(options.storeRoot)
  const absPath = evidenceFilePath(storagePath, options.storeRoot)
  await mkdir(root, { recursive: true })
  await writeFile(absPath, input.bytes, { mode: 0o600 })
  await chmod(absPath, 0o600)

  const created = await db.expertCredentialEvidence.create({
    data: {
      profileId: profile.id,
      kind: input.kind,
      fileName: input.fileName.slice(0, 200),
      byteSize: input.bytes.length,
      sha256,
      mimeType: mime,
      storagePath,
      retentionState: 'ACTIVE',
      uploadedByStudentId: actor.studentId,
    },
  })
  await actorEvent(db, profile.id, 'EVIDENCE_UPLOADED', 'REVIEWER', actor.studentId, `credential evidence uploaded (${input.kind})`, {
    evidenceId: created.id,
    kind: input.kind,
    fileName: created.fileName,
    byteSize: created.byteSize,
    sha256,
    mimeType: mime,
  })
  return { ok: true, evidence: created, profile }
}

/** Purge one ACTIVE evidence row owned by the applicant (file bytes removed). */
export async function purgeOwnEvidence(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
  evidenceId: string,
  reason: string,
  options: { storeRoot?: string } = {},
): Promise<ApplicationOpResult<EvidenceRow>> {
  const evidence = await db.expertCredentialEvidence.findUnique({ where: { id: evidenceId } })
  if (!evidence) return { ok: false, status: 404, error: 'evidence not found' }
  if (evidence.uploadedByStudentId !== actor.studentId) {
    return { ok: false, status: 403, error: 'this evidence belongs to a different account' }
  }
  if (evidence.retentionState !== 'ACTIVE') {
    return { ok: false, status: 409, error: 'evidence is already purged' }
  }
  return purgeEvidenceRow(db, evidence, reason, options)
}

async function purgeEvidenceRow(
  db: ApplicationsDb,
  evidence: EvidenceRow,
  reason: string,
  options: { storeRoot?: string } = {},
): Promise<ApplicationOpResult<EvidenceRow>> {
  try {
    await unlink(evidenceFilePath(evidence.storagePath, options.storeRoot))
  } catch {
    // The row still flips to PURGED — a missing file must never hide that the
    // content is no longer retained (honest retention state).
  }
  const updated = await db.expertCredentialEvidence.update({
    where: { id: evidence.id },
    data: { retentionState: 'PURGED', purgedAt: new Date(), purgedReason: reason.slice(0, 500) },
  })
  await actorEvent(db, evidence.profileId, 'EVIDENCE_PURGED', 'REVIEWER', evidence.uploadedByStudentId, reason.slice(0, 2000), {
    evidenceId: evidence.id,
    sha256: evidence.sha256,
    kind: evidence.kind,
  })
  return { ok: true, evidence: updated }
}

export async function listApplicationEvidence(db: ApplicationsDb, profileId: string): Promise<EvidenceRow[]> {
  return db.expertCredentialEvidence.findMany({ where: { profileId }, orderBy: { createdAt: 'asc' } }) as Promise<EvidenceRow[]>
}

// ─── Information-request loop ──────────────────────────────────────────────────

const infoRequestSchema = z.object({
  requestText: z.string().min(20, 'information request must be specific (min 20 chars)').max(2000),
}).strict()

/** Administrator requests additional information/evidence from an applicant. */
export async function requestAdditionalInfo(
  db: ApplicationsDb,
  admin: { studentId: string; displayName: string },
  profileId: string,
  input: unknown,
): Promise<ApplicationOpResult<InfoRequestRow>> {
  const parsed = infoRequestSchema.safeParse(input)
  if (!parsed.success) {
    const first = parsed.error.issues[0]
    return { ok: false, status: 400, error: `invalid information request: ${first?.message ?? 'schema mismatch'}` }
  }
  const profile = await db.expertReviewerProfile.findUnique({ where: { id: profileId } })
  if (!profile) return { ok: false, status: 404, error: 'expert application not found' }
  if (!OPEN_APPLICATION_STATUSES.includes(profile.status as (typeof OPEN_APPLICATION_STATUSES)[number])) {
    return { ok: false, status: 409, error: `application is ${profile.status} — information requests apply to open applications` }
  }
  const created = await db.expertApplicationInfoRequest.create({
    data: {
      profileId: profile.id,
      requestText: parsed.data.requestText,
      status: 'OPEN',
      requestedByAdminId: admin.studentId,
    },
  })
  await actorEvent(db, profile.id, 'INFO_REQUESTED', 'ADMIN', admin.studentId, 'administrator requested additional information/evidence', {
    requestId: created.id,
    requestText: created.requestText.slice(0, 500),
  })
  return { ok: true, request: created }
}

const infoAnswerSchema = z.object({
  responseText: z.string().min(4, 'response required').max(4000),
}).strict()

/** Applicant answers an open information request on their own application. */
export async function answerInfoRequest(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
  requestId: string,
  input: unknown,
): Promise<ApplicationOpResult<InfoRequestRow>> {
  const parsed = infoAnswerSchema.safeParse(input)
  if (!parsed.success) {
    const first = parsed.error.issues[0]
    return { ok: false, status: 400, error: `invalid response: ${first?.message ?? 'schema mismatch'}` }
  }
  const request = await db.expertApplicationInfoRequest.findUnique({ where: { id: requestId } })
  if (!request) return { ok: false, status: 404, error: 'information request not found' }
  const profile = await db.expertReviewerProfile.findUnique({ where: { id: request.profileId } })
  if (!profile || profile.studentId !== actor.studentId) {
    return { ok: false, status: 403, error: 'this information request belongs to a different application' }
  }
  if (request.status !== 'OPEN') {
    return { ok: false, status: 409, error: 'information request is already answered' }
  }
  const updated = await db.expertApplicationInfoRequest.update({
    where: { id: request.id },
    data: { status: 'ANSWERED', responseText: parsed.data.responseText, answeredAt: new Date() },
  })
  await actorEvent(db, profile.id, 'INFO_ANSWERED', 'REVIEWER', actor.studentId, 'applicant answered the administrator information request', {
    requestId: request.id,
    responseLength: parsed.data.responseText.length,
  })
  return { ok: true, request: updated }
}

export async function listApplicationInfoRequests(db: ApplicationsDb, profileId: string): Promise<InfoRequestRow[]> {
  return db.expertApplicationInfoRequest.findMany({ where: { profileId }, orderBy: { requestedAt: 'asc' } }) as Promise<InfoRequestRow[]>
}

// ─── Withdrawal (applicant-initiated; retention rules applied) ─────────────────

/**
 * Withdraw an open application. Uses the strict CI-5 transition table
 * (APPLICATION_PENDING/QUALIFICATION_REVIEW → WITHDRAWN; WITHDRAWN is
 * terminal). Every ACTIVE evidence file is purged (bytes removed, metadata +
 * hash retained) per the retention rules; the audit trail is preserved.
 */
export async function withdrawApplication(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
  input: unknown,
  options: { storeRoot?: string } = {},
): Promise<ApplicationOpResult> {
  const schema = z.object({ reason: z.string().min(4).max(1000).optional() }).strict()
  const parsed = schema.safeParse(input ?? {})
  if (!parsed.success) return { ok: false, status: 400, error: 'invalid withdrawal payload' }
  const profile = await db.expertReviewerProfile.findUnique({ where: { studentId: actor.studentId } })
  if (!profile) return { ok: false, status: 404, error: 'no expert application exists for this account' }
  const allowed = REVIEWER_TRANSITIONS[profile.status as keyof typeof REVIEWER_TRANSITIONS] ?? []
  if (!allowed.includes('WITHDRAWN')) {
    return { ok: false, status: 409, error: `application is ${profile.status} — withdrawal is only possible while the application is open` }
  }
  const evidence = await db.expertCredentialEvidence.findMany({ where: { profileId: profile.id, retentionState: 'ACTIVE' } })
  for (const row of evidence) {
    await purgeEvidenceRow(db, row, parsed.data.reason || 'application withdrawn by applicant — evidence purged per retention rules', options)
  }
  const updated = await db.expertReviewerProfile.update({
    where: { id: profile.id },
    data: { status: 'WITHDRAWN' },
  })
  await actorEvent(db, profile.id, 'APPLICATION_WITHDRAWN', 'REVIEWER', actor.studentId, (parsed.data.reason || 'application withdrawn by applicant').slice(0, 2000), {
    purgedEvidenceCount: evidence.length,
  })
  return { ok: true, profile: updated }
}

/** Full application detail for the applicant's own view (metadata only). */
export async function getApplicationDetail(
  db: ApplicationsDb,
  actor: { studentId: string; displayName: string },
): Promise<{ profile: ReviewerProfileRow; specialties: string[]; evidence: EvidenceRow[]; infoRequests: InfoRequestRow[] } | null> {
  const profile = await db.expertReviewerProfile.findUnique({ where: { studentId: actor.studentId } })
  if (!profile) return null
  const [evidence, infoRequests] = await Promise.all([
    listApplicationEvidence(db, profile.id),
    listApplicationInfoRequests(db, profile.id),
  ])
  return { profile, specialties: parseJsonArray(profile.specialtiesJson), evidence, infoRequests }
}

/** Existence check used by routes (never leaks file paths). */
export async function getActiveEvidenceFile(db: ApplicationsDb, evidenceId: string): Promise<{ row: EvidenceRow; absolutePath: string } | null> {
  const row = await db.expertCredentialEvidence.findUnique({ where: { id: evidenceId } })
  if (!row) return null
  try {
    const abs = evidenceFilePath(row.storagePath)
    await stat(abs)
    return { row, absolutePath: abs }
  } catch {
    return null
  }
}
