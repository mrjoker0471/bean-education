import { PrismaClient } from '@prisma/client';
const db = new PrismaClient();
const doc = await db.studyDocument.findFirst({ orderBy: { createdAt: 'desc' } });
const analysis = JSON.parse(doc.analysisJson || 'null');
console.log('=== RAW TOPIC[0..3] ===');
console.log(JSON.stringify(analysis.topics.slice(0, 4), null, 2));
console.log('=== keyPages ===', JSON.stringify(analysis.keyPages).slice(0, 400));
console.log('=== unreadableSections ===', JSON.stringify(analysis.unreadableSections));
console.log('=== definitions[0] ===', JSON.stringify(analysis.definitions?.[0]));
console.log('=== extraction stats ===');
const ex = JSON.parse(doc.extractionJson || '[]');
console.log('pages in extraction:', ex.length);
console.log('chars per page (first 30):', ex.slice(0,30).map(p => `${p.page}:${p.chars}${p.scanned?'(scanned)':''}`).join(' '));
await db.$disconnect();
