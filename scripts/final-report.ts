import { PrismaClient } from '@prisma/client'
const db = new PrismaClient()
async function main() {
  console.log('=== CATALOGUE ===')
  console.log('categories:', await db.category.count())
  console.log('exams total:', await db.exam.count())
  console.log('featured:', await db.exam.count({ where: { featured: true } }))
  const byCat = await db.exam.groupBy({ by: ['categorySlug'], _count: { _all: true } })
  console.log('byCategory:', byCat.map(c => `${c.categorySlug}=${c._count._all}`).join(', '))
  const byStatus = await db.exam.groupBy({ by: ['syllabusStatus'], _count: { _all: true } })
  console.log('syllabusStatus:', byStatus.map(c => `${c.syllabusStatus}=${c._count._all}`).join(', '))
  console.log('stages:', await db.stage.count(), '| subjects:', await db.subject.count(), '| units:', await db.unit.count(), '| topics:', await db.topic.count())
  console.log('=== CONTENT ===')
  console.log('unique notes (canonical):', (await db.$queryRawUnsafe<{c: bigint}>('SELECT COUNT(DISTINCT canonicalSlug) as c FROM Note'))[0].c)
  console.log('note-topic links:', await db.note.count())
  console.log('questions total:', await db.question.count())
  const qSrc = await db.question.groupBy({ by: ['sourceType'], _count: { _all: true } })
  console.log('questionsBySource:', qSrc.map(c => `${c.sourceType}=${c._count._all}`).join(', '))
  console.log('resources rows:', await db.resource.count())
  const rStatus = await db.resource.groupBy({ by: ['verificationStatus'], _count: { _all: true } })
  console.log('resourcesByStatus:', rStatus.map(c => `${c.verificationStatus}=${c._count._all}`).join(', '))
  const rType = await db.resource.groupBy({ by: ['type'], _count: { _all: true } })
  console.log('resourcesByType:', rType.map(c => `${c.type}=${c._count._all}`).join(', '))
  console.log('templates:', await db.testTemplate.count())
  const tType = await db.testTemplate.groupBy({ by: ['type'], _count: { _all: true } })
  console.log('templatesByType:', tType.map(c => `${c.type}=${c._count._all}`).join(', '))
  console.log('attempts:', await db.attempt.count(), '(all from verification testing)')
  const withPattern = await db.stage.count({ where: { patternJson: { not: null } } })
  console.log('stages with recorded pattern:', withPattern)
  await db.$disconnect()
}
main()
